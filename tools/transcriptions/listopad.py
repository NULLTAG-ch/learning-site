import json, re, sys

NAMES = {'C':0,'D':2,'E':4,'F':5,'G':7,'A':9,'B':11}
def p(n):
    m = re.fullmatch(r'([A-G])(##|#|n|b)?(-?\d)', n)
    acc = {'#':1,'##':2,'b':-1,'n':0,None:0}[m.group(2)]
    return 12*(int(m.group(3))+1) + NAMES[m.group(1)] + acc

# Taktanfaenge: 4/4, Takt 45 im 2/4
def start(bar):
    if bar <= 45: return (bar-1)*4
    return 178 + (bar-46)*4

R, L = {}, {}           # bar -> [(off, dur, [pitches])]
def ev(store, bar, *items):
    store.setdefault(bar, [])
    for off, dur, ps in items:
        store[bar].append((off, dur, [p(x) for x in ps.split()]))

