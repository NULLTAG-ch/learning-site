notes = []
for store, hand in ((R,1),(L,0)):
    for bar, evs in store.items():
        s = start(bar)
        for off, dur, ps in evs:
            for m in ps:
                notes.append([round(s+off, 4), round(dur, 4), m, hand])
END = start(53) + 4
notes = [n for n in notes if n[0] < END]
for n in notes: n[1] = min(n[1], END - n[0])
# gleiche Tonhoehe in derselben Hand: Haltenote endet beim Neuanschlag
notes.sort(key=lambda n: (n[3], n[2], n[0]))
ded = []
for n in notes:
    if ded and ded[-1][2:] == n[2:] and ded[-1][0] == n[0]:
        ded[-1][1] = max(ded[-1][1], n[1]); continue
    if ded and ded[-1][2:] == n[2:] and ded[-1][0] + ded[-1][1] > n[0]:
        ded[-1][1] = round(n[0] - ded[-1][0], 4)
    ded.append(n)
notes = sorted(ded, key=lambda n: (n[0], n[2]))
for n in notes:
    for i in (0, 1):
        if float(n[i]).is_integer(): n[i] = int(n[i])
        else: n[i] = round(n[i], 3)
json.dump(notes, open(sys.argv[1], 'w'))
print(len(notes), 'Noten, Ende', END, 'RH', sum(n[3] for n in notes),
      'Ambitus', min(n[2] for n in notes), max(n[2] for n in notes))
