# ---------- Linke Hand ----------
def lh(bar, *items): ev(L, bar, *items)
def lh_dot(bar, a, b, lo=None):          # Viertel + punktierte Achtel/16tel
    lh(bar, (0,1,a),(1,.75,a),(1.75,.25,a),(2,1,b),(3,.75,b),(3.75,.25,b))
    if lo: lh(bar, (0,2,lo[0]),(2,2,lo[1]))
